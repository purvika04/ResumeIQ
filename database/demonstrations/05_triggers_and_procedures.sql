\echo '----------------------------------------------------------------------'
\echo 'DEMO 5.1: User-Defined Function (UDF): fn_calculate_candidate_experience_tenure'
\echo '----------------------------------------------------------------------'

SELECT 
    c.id AS candidate_id,
    c.name,
    c.total_experience_years AS stored_years,
    fn_calculate_candidate_experience_tenure(c.id) AS calculated_years,
    COUNT(cx.id) AS experience_records_count
FROM candidates c
LEFT JOIN candidate_experiences cx ON c.id = cx.candidate_id
GROUP BY c.id, c.name, c.total_experience_years
ORDER BY calculated_years DESC
LIMIT 5;

\echo ''
\echo '----------------------------------------------------------------------'
\echo 'DEMO 5.2: Audit Trigger Execution Verification (INSERT, UPDATE, DELETE)'
