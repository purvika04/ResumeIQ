-- Inspect the most recent audit records generated by the trigger
SELECT 
    log_id,
    action_type,
    screening_id,
    candidate_id,
    job_id,
    old_overall_score,
    new_overall_score,
    changed_by,
    changed_at
FROM audit_screening_logs
ORDER BY log_id DESC
LIMIT 6;

\echo ''
\echo '----------------------------------------------------------------------'
\echo 'DEMO 5.3: Stored Procedure: sp_batch_recalculate_scores'
\echo 'Recalculating screening scores in-database with custom scoring weights'
\echo '----------------------------------------------------------------------'

-- Sample job ID
SELECT id AS target_job, title FROM jobs LIMIT 1;

-- Call stored procedure with weights: 30% semantic, 40% required, 20% preferred, 10% exp
DO \$\$
DECLARE
    v_job VARCHAR;
BEGIN
    SELECT id INTO v_job FROM jobs LIMIT 1;
    CALL sp_batch_recalculate_scores(v_job, 0.30, 0.40, 0.20, 0.10);
END \$\$;

-- Inspect newly recalculated scores for that job
SELECT 
    sr.candidate_id,
    c.name,
    sr.overall_score,
    sr.semantic_score,
    sr.required_skill_score,
    sr.preferred_skill_score,
    sr.experience_score
FROM screening_results sr
JOIN candidates c ON sr.candidate_id = c.id
WHERE sr.job_id = (SELECT id FROM jobs LIMIT 1)
ORDER BY sr.overall_score DESC
LIMIT 5;
